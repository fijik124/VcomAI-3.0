import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { addonAssertions } from '../tools/addon-project.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const suite = process.argv[2] || 'all';
const world = suite === 'cqb-floors' ? 'Altis' : 'VR';
const folder = path.join(root, `build/runtime/VCM_Regression.${world}`);
const addon = process.argv.includes('--addon');
assert.ok(['all','safety','tactics','vehicle','performance','advanced','cqb','cqb-floors'].includes(suite));
const seconds = Number(process.argv.find(arg => arg.startsWith('--duration='))?.split('=')[1] || 60);
assert.ok(Number.isInteger(seconds) && seconds >= 30 && seconds <= 1800);
assert.equal(path.dirname(folder), path.join(root,'build/runtime'));
fs.rmSync(folder, { recursive: true, force: true });
fs.mkdirSync(folder, { recursive: true });
fs.writeFileSync(path.join(folder,'addon-layout.sqf'),addon ? addonAssertions() : '// Mission-script mode has no addon modules.\n');
if (!addon) fs.cpSync(path.join(root, 'Vcom'), path.join(folder, 'Vcom'), { recursive: true });
let description = fs.readFileSync(path.join(root,'description.ext'),'utf8');
if (addon) description = description.replace(/class CfgFunctions\s*\{[\s\S]*?\};/,'');
fs.writeFileSync(path.join(folder, 'description.ext'),description);
fs.appendFileSync(path.join(folder, 'description.ext'), '\nclass Header { gameType="COOP"; minPlayers=1; maxPlayers=1; };\n');
fs.copyFileSync(path.join(root, 'tests/regression.sqf'), path.join(folder, 'regression.sqf'));
fs.copyFileSync(path.join(root, 'tests/fire-movement.sqf'), path.join(folder, 'fire-movement.sqf'));
fs.copyFileSync(path.join(root, 'tests/cover.sqf'), path.join(folder, 'cover.sqf'));
fs.copyFileSync(path.join(root, 'tests/safety.sqf'), path.join(folder, 'safety.sqf'));
fs.copyFileSync(path.join(root, 'tests/tactics.sqf'), path.join(folder, 'tactics.sqf'));
fs.copyFileSync(path.join(root, 'tests/vehicle.sqf'), path.join(folder, 'vehicle.sqf'));
fs.copyFileSync(path.join(root, 'tests/performance.sqf'), path.join(folder, 'performance.sqf'));
fs.copyFileSync(path.join(root, 'tests/advanced.sqf'), path.join(folder, 'advanced.sqf'));
fs.copyFileSync(path.join(root, 'tests/coordination.sqf'), path.join(folder, 'coordination.sqf'));
fs.copyFileSync(path.join(root, 'tests/evacuation.sqf'), path.join(folder, 'evacuation.sqf'));
fs.copyFileSync(path.join(root, 'tests/cqb.sqf'), path.join(folder, 'cqb.sqf'));
fs.copyFileSync(path.join(root, 'tests/cqb-control.sqf'), path.join(folder, 'cqb-control.sqf'));
fs.copyFileSync(path.join(root, 'tests/cqb-floors.sqf'), path.join(folder, 'cqb-floors.sqf'));
if (suite !== 'all') fs.writeFileSync(path.join(folder,'regression.sqf'), `if (!isServer) exitWith {};
waitUntil {sleep 0.1; missionNamespace getVariable ["VCM_ServerReady",false]};
VCM_TestCount=0; VCM_TestFailures=0;
private _assert={params ["_condition","_name"]; VCM_TestCount=VCM_TestCount+1; if (!_condition) then {VCM_TestFailures=VCM_TestFailures+1}; diag_log format ["VCM_TEST_%1: %2",["FAIL","PASS"] select _condition,_name]};
[] call compile preprocessFileLineNumbers "addon-layout.sqf";
VCM_PerfSeconds=${seconds}; VCM_PerfEnabled=${!process.argv.includes('--vanilla')};
[] call compile preprocessFileLineNumbers "${suite}.sqf";
diag_log format ["VCM_TEST_DONE: %1 checks, %2 failures",VCM_TestCount,VCM_TestFailures];
`);
fs.writeFileSync(path.join(folder, 'init.sqf'), (addon ? '' : '[] execVM "Vcom\\VcomInit.sqf";\n') + '[] execVM "regression.sqf";\n');
fs.writeFileSync(path.join(folder, 'mission.sqm'), `version=12;
class Mission {
 addOns[]={"A3_Characters_F_BLUFOR","A3_Map_${world}"};
 addOnsAuto[]={"A3_Characters_F_BLUFOR","A3_Map_${world}"};
 randomSeed=1;
 class Intel { briefingName="VCOM regression"; resistanceWest=0; resistanceEast=1; startWeather=0; forecastWeather=0; year=2035; month=6; day=24; hour=12; minute=0; };
 class Groups { items=1; class Item0 { side="WEST"; class Vehicles { items=1; class Item0 { position[]={500,0,500}; azimut=0; id=0; side="WEST"; vehicle="B_Soldier_F"; player="PLAY CDG"; leader=1; skill=0.6; init="(group this) setVariable ['Vcm_Disable',true];"; }; }; }; };
};
`);
const template = folder.replaceAll('\\', '/');
fs.writeFileSync(path.join(root, 'build/runtime/server.cfg'), `hostname="VCOM local regression";
password="vcom-local-tests";
steamProtocolMaxDataSize=1024;
reportingIP="";
persistent=1;
BattlEye=0;
verifySignatures=0;
allowedFilePatching=0;
maxPlayers=1;
class Missions { class Regression { template="${template}"; difficulty="Regular"; }; };
`);
console.log(folder);
